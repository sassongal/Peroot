/**
 * Arabic and Russian vocabulary for the prompt scorers.
 *
 * The scorers in this folder grew up bilingual (Hebrew + English) and judge a
 * prompt by the words it uses: "אתה מומחה", "write a", "קהל יעד", "avoid".
 * A perfectly good Arabic or Russian prompt used to score near zero on every
 * lexical dimension because none of its words were in the lists (languages
 * spec, 2026-09-02, B4: "the scorer must work there too").
 *
 * This module is the one place those two languages live. Each entry is a
 * regex SOURCE fragment (a string, no delimiters, no flags) so a scorer can
 * append it to its existing pattern with `i18n(re, I18N.audience)` and keep
 * its Hebrew/English behaviour byte-for-byte.
 *
 * Conventions:
 * - Fragments are alternations without outer anchors; the caller's regex
 *   flags (`i`, `m`) apply to them too. JS `/i` folds Cyrillic case, so
 *   "Напиши" and "напиши" both match a lower-case fragment.
 * - Arabic is matched on stems where inflection is heavy (تنسيق matches
 *   التنسيق, بتنسيق). Hamza variants are written out where the prompt
 *   engines and real users differ (أنشئ / انشئ).
 * - Russian is matched on stems too (аудитори covers аудитория / аудитории).
 */

